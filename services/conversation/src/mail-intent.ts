/**
 * 「メール確認して」を、決まった読み取りの仕事にする。純粋関数。
 *
 * 以前はモデルへ渡るだけで受信箱を読まず、「受信箱は見ていません」と答えていた（LINE 2026-11-01）。
 * 文全体がメールの確認のときだけ受ける。相手や操作の指定があるもの（返信・送信・「田中さんの」）は今までの経路に任せる。
 */
const CHECK =
  /^(?:(?:今日|きょう|最近|新しい|新着|届いた|来た|いま|今)の?\s*)*(?:gmail|outlook|メール|受信箱|受信トレイ|未読(?:メール)?)\s*(?:を|は|が)?\s*(?:(?:確認|チェック)(?:して|する|お願い)?|見て|みて|見せて|読んで|教えて|あ(?:る|ります)|(?:来|き|届い)て|どう|[?？]|$)/i;
const OTHER = /送|返信|返事|下書き|削除|消して|転送|設定|アプリ|開いて/;

export function isMailCheck(text: string): boolean {
  const t = text.trim();
  return t.length <= 30 && !OTHER.test(t) && CHECK.test(t);
}
